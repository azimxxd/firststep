import type { Intent } from "@/types/safety";

const intentPatterns: Array<[Intent, RegExp]> = [
  ["SELF_HARM_RISK", /не хочу жить|хочу умереть|поконч[а-яё]*\s+с\s+собой|наложить на себя руки|свести сч[её]ты с жизнью|суицид|убить себя|лучше бы меня не было|уснуть и не проснуться|self[- ]?harm|kill myself|want to die|өмір сүргім келмейді|өзімді өлтіремін|өзіме зиян|өлгім келеді/i],
  ["PANIC", /паник|панич|не могу дышать|5-4-3-2-1/i],
  ["ANXIETY", /тревог|тревож|страшно|волнуюсь|пережива|беспокоюсь|қорқам|уайым/i],
  ["ACADEMIC_STRESS", /экзамен|уч[её]б|сесс|долг|оцен|успева|академическ|балл|отчисл|пересдач|предмет|завал|университет|колледж|дедлайн|срок|домашк|задан|задач|практик|проект|реферат|курсова|диплом|лаборатор|семинар|зач[её]т|прокраст|преподав|стипенд|общежит|емтихан|оқу|үлгерім|баға|пән|университет|колледж|мерзім|тапсырма|жоба|жатақхана/i],
  // "одна" is deliberately absent: as a substring it also matches "однажды", "однако" and "одна задача".
  ["LONELINESS", /одинок|один в |одна в |никого не знаю|не с кем|нет друзей|нет близких|никто не понимает|никому не нужен|сам по себе|сама по себе|скучаю|написать (?:близк|друг|одногрупп|куратор)|просить о поддержке|жалғыз|досым жоқ|ешкім жоқ|сөйлесетін.{0,12}жоқ|жақын.*жаз|қолдау сұра/i],
  ["BULLYING", /травят|буллинг|издеваются|обижают|қорқытады|мазақ/i],
  ["FAMILY_PRESSURE", /родител|семья|мама|папа|давят|ата-анам|отбасым/i],
  ["GENERAL_DISTRESS", /плохо|тяжело|груст|устал|выгор|нет сил|не справля|больно|қиын|мұң|шарша|күшім жоқ/i],
];

export function classifyIntent(message: string): Intent[] {
  const intents = intentPatterns.filter(([, pattern]) => pattern.test(message)).map(([intent]) => intent);
  return intents.length ? intents : ["UNKNOWN"];
}
